package com.eza.spicyex.lyrics.language.mandarin;

import com.eza.spicyex.lyrics.language.MandarinReadings;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;

import org.junit.BeforeClass;
import org.junit.Test;

import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;

/**
 * Cross-implementation gate for the handwritten Java g2pM engine.
 *
 * <p>Fixtures are generated by the pinned TypeScript engine at cjk-labs {@code 24c494c} over
 * public probe sentences and public CPP test rows only; no captured lyric text is stored here.
 * The numeric fixture pins dense logits from the same weights. Per-logit tolerance is 1e-5
 * absolute, as required by the port contract.
 */
public class MandarinG2pMParityTest {
    private static final String PACK = "mandarin-g2pm@991b24c1dd60ea8190ca110a608bbd084af8ba3768614662592763ebac9c05bf";
    private static final double LOGIT_TOLERANCE = 1e-5;
    private static MandarinReader reader;

    @BeforeClass
    public static void loadReader() throws Exception {
        reader = MandarinReadings.reader();
        assertNotNull(reader);
    }

    @Test
    public void bundledPackMatchesThePinnedManifestAndCounts() throws Exception {
        assertEquals(PACK, reader.assetVersion());
        MandarinG2pM engine = reader.engine();
        assertEquals(44_440, engine.characterCount());
        assertEquals(317_610, engine.phraseCount());
        assertEquals(10_714, engine.digestCount());
        assertEquals(3_222, engine.shadowCount());
        assertEquals(876, engine.classCount());
        assertEquals(5_398, engine.vocabularySize());
    }

    @Test
    public void probeReadingsMatchThePinnedTypeScriptEngine() throws Exception {
        JsonArray probes = reference().getAsJsonArray("probes");
        assertEquals(15, probes.size());
        for (JsonElement element : probes) {
            JsonObject probe = element.getAsJsonObject();
            String text = probe.get("text").getAsString();
            assertReadings("probe " + text, probe.getAsJsonArray("readings"), reader.engine().read(text));
        }
    }

    @Test
    public void publicCppRowsMatchThePinnedTypeScriptEngine() throws Exception {
        JsonArray rows = reference().getAsJsonArray("cpp");
        assertEquals(8, rows.size());
        for (JsonElement element : rows) {
            JsonObject row = element.getAsJsonObject();
            String text = row.get("text").getAsString();
            MandarinG2pM.Line line = reader.engine().read(text);
            assertReadings("cpp " + row.get("id").getAsString(), row.getAsJsonArray("readings"), line);
            int target = row.get("targetIndex").getAsInt();
            assertEquals(row.get("id").getAsString(), row.get("gold").getAsString(),
                    line.syllables.get(target).raw);
        }
    }

    @Test
    public void denseLogitsMatchTypeScriptWithinTolerance() throws Exception {
        JsonObject fixture = parse("mandarin-g2pm/numeric-fixture.json").getAsJsonObject();
        double maximum = 0;
        int compared = 0;
        for (JsonElement element : fixture.getAsJsonArray("cases")) {
            JsonObject item = element.getAsJsonObject();
            String text = item.get("text").getAsString();
            MandarinG2pM.Line line = reader.engine().read(text);
            assertReadings("numeric " + text, item.getAsJsonArray("readings"), line);
            JsonArray positionsJson = item.getAsJsonArray("positions");
            int[] positions = new int[positionsJson.size()];
            for (int at = 0; at < positions.length; at++) positions[at] = positionsJson.get(at).getAsInt();
            float[][] actual = reader.engine().logits(text, positions);
            JsonArray expected = item.getAsJsonArray("logits");
            for (int at = 0; at < actual.length; at++) {
                JsonArray row = expected.get(at).getAsJsonArray();
                assertEquals(876, row.size());
                for (int classIndex = 0; classIndex < row.size(); classIndex++) {
                    double difference = Math.abs(actual[at][classIndex] - row.get(classIndex).getAsDouble());
                    maximum = Math.max(maximum, difference);
                    compared++;
                }
            }
        }
        assertTrue("compared " + compared + " logits", compared > 7_000);
        assertTrue("max absolute logit difference " + maximum, maximum <= LOGIT_TOLERANCE);
    }

    @Test
    public void wholeInputPhraseEntryIsAuthoritative() {
        MandarinG2pM.Line line = reader.engine().read("\u7761\u5F97\u7740");
        String[] expected = {"shui4", "de5", "zhao2"};
        for (int index = 0; index < expected.length; index++) {
            assertEquals(expected[index], line.syllables.get(index).raw);
            assertEquals("phrase", line.syllables.get(index).basis);
        }
    }

    @Test
    public void phraseFillOnlySuppliesPositionsTheModelDidNotDecide() {
        MandarinG2pM.Line line = reader.engine().read("\u6211\u7684\u54E5\u54E5");
        assertEquals("model", line.syllables.get(1).basis);
        assertEquals("de5", line.syllables.get(1).raw);
        assertEquals("phrase", line.syllables.get(3).basis);
        assertEquals("ge5", line.syllables.get(3).raw);
    }

    @Test
    public void noPerWordExceptionOrPotentialComplementRuleRemains() {
        assertEquals("qu4 bu4 le5", raws("\u53BB\u4E0D\u4E86"));
        assertEquals("qu4 le5", raws("\u53BB\u4E86"));
        assertEquals("de2 le5 ba5", raws("\u5F97\u4E86\u5427"));
        // 看得见 keeps the model/source reading. The neutral de gap is not patched.
        assertEquals("kan4 de2 jian4", raws("\u770B\u5F97\u89C1"));
    }

    @Test
    public void digestCoverageComesFromTheSourceCharacterOnly() {
        // 為 has no digest entry. The 为 shadow may feed the model and phrase lookup, but it must
        // not lend polyphone coverage; the pinyin-data default wei4 survives.
        MandarinG2pM.Line wei = reader.engine().read("\u70BA");
        assertEquals("wei4", wei.syllables.get(0).raw);
        assertEquals("character", wei.syllables.get(0).basis);
        // 乾's own digest is single-reading, so 干's gan4/gan1 alternatives must not reopen it.
        MandarinG2pM.Line qian = reader.engine().read("\u4E7E");
        assertEquals("qian2", qian.syllables.get(0).raw);
        assertEquals("character", qian.syllables.get(0).basis);
        // 儁 has no digest at all; the 俊 shadow must not decide it.
        MandarinG2pM.Line jun = reader.engine().read("\u5101");
        assertEquals("jun4", jun.syllables.get(0).raw);
        assertEquals("character", jun.syllables.get(0).basis);
    }

    @Test
    public void sourcePolyphoneStillReachesTheModel() {
        // 术 is polyphonic in its own digest entry and present in the model vocabulary.
        MandarinG2pM.Line line = reader.engine().read("\u672F");
        assertEquals("shu4", line.syllables.get(0).raw);
        assertEquals("model", line.syllables.get(0).basis);
    }

    @Test
    public void neutralZhaoSurvivesTheFrozenEzaLayer() {
        MandarinReadingLine line = reader.read("\u7761\u5F97\u7740");
        List<List<String>> surface = MandarinSandhi.surface(line);
        assertEquals("zhao2", surface.get(surface.size() - 1).get(surface.get(surface.size() - 1).size() - 1));
        assertTrue(MandarinEza.render(line, surface, true).contains("zh\u00E1o"));
    }

    private static String raws(String text) {
        StringBuilder out = new StringBuilder();
        for (MandarinG2pM.Syllable syllable : reader.engine().read(text).syllables) {
            if (out.length() > 0) out.append(' ');
            out.append(syllable.status == MandarinG2pM.Status.READING
                    ? syllable.raw : "<" + syllable.status + ">");
        }
        return out.toString();
    }

    private static void assertReadings(String label, JsonArray expected, MandarinG2pM.Line line) {
        assertEquals(label + " alignment", expected.size(), line.syllables.size());
        for (int index = 0; index < expected.size(); index++) {
            JsonElement value = expected.get(index);
            String wanted = value == null || value.isJsonNull() ? null : value.getAsString();
            String actual = line.syllables.get(index).status == MandarinG2pM.Status.READING
                    ? line.syllables.get(index).raw : null;
            assertEquals(label + " @" + index, wanted, actual);
        }
    }

    private static JsonObject reference() throws IOException {
        return parse("mandarin-g2pm/reference.json").getAsJsonObject();
    }

    private static JsonElement parse(String path) throws IOException {
        try (InputStream in = MandarinG2pMParityTest.class.getResourceAsStream("/" + path)) {
            if (in == null) throw new IOException("Missing test resource: " + path);
            return JsonParser.parseReader(new InputStreamReader(in, StandardCharsets.UTF_8));
        }
    }
}
